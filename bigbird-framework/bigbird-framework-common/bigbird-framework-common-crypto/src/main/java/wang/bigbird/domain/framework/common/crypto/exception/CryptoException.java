package wang.bigbird.domain.framework.common.crypto.exception;

/**
 * 封装的加解密异常
 *
 * @author Bigbird
 */
public class CryptoException extends RuntimeException {

    private static final long serialVersionUID = 7402827694160776875L;

    public CryptoException() {
        super();
    }

    public CryptoException(String message) {
        super(message);
    }

    public CryptoException(String message, Throwable cause) {
        super(message, cause);
    }
}
